namespace Lev.Git.Preview
{
    /// <summary>
    /// Публичный API превью изменений ассетов.
    ///
    /// Три точки расширения, каждая находится сама через TypeCache — достаточно
    /// унаследоваться в любой редакторской сборке проекта или пакета:
    ///
    /// <list type="bullet">
    /// <item><see cref="AssetLoader"/> — как превратить байты версии из git в
    /// объекты Unity. Нужен только для своих форматов: YAML-ассеты, PNG/JPEG/TGA,
    /// звук, префабы и модели пакет читает сам.</item>
    /// <item><see cref="ChangeDescriber{T}"/> — что изменилось, словами инспектора:
    /// вкладка «Изменения», откат пунктов, миниатюры списка.</item>
    /// <item><see cref="AssetPresenter"/> — как нарисовать версию: вкладка «Вид»,
    /// «История ассета», конфликты, миниатюры. Режимы сравнения (рядом, шторка,
    /// наложение, разница), лупу и воспроизведение даёт панель — показ только
    /// рисует одну сторону и говорит, что умеет.</item>
    /// </list>
    ///
    /// Выбор — как у CustomEditor: побеждает самый производный Target, при
    /// равенстве — больший Priority. Исключение в своём коде не ломает панель:
    /// она покажет текст ошибки и одно предупреждение в консоли.
    ///
    /// Всё вызывается на главном потоке. Объекты версии из git — временные и
    /// скрытые; панель уничтожает LoadedAsset.Main и All сама, а Data, если
    /// реализует IDisposable, освобождается вместе с версией.
    /// </summary>
    public static class PreviewApi
    {
        /// <summary>
        /// Версия контракта. Растёт, когда меняется сигнатура публичного члена;
        /// новые виртуальные члены с поведением по умолчанию её не меняют.
        /// </summary>
        public const int Version = 1;
    }
}
